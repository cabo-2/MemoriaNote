using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using McMaster.Extensions.CommandLineUtils;

namespace MemoriaNote.Cli
{
    /// <summary>Generates a deterministic static zsh completion from command metadata.</summary>
    internal static class ZshCompletionGenerator
    {
        enum CompletionKind
        {
            None,
            File,
            Directory,
            Values
        }

        sealed class CompletionHint
        {
            internal CompletionHint(
                CompletionKind kind,
                params string[] values)
            {
                Kind = kind;
                Values = values;
            }

            internal CompletionKind Kind { get; }

            internal IReadOnlyList<string> Values { get; }
        }

        static readonly IReadOnlyDictionary<string, CompletionHint> Hints =
            new Dictionary<string, CompletionHint>(StringComparer.Ordinal)
            {
                ["mn notebooks backup argument archive"] =
                    new CompletionHint(CompletionKind.File),
                ["mn notebooks restore argument archive"] =
                    new CompletionHint(CompletionKind.File),
                ["mn notebooks import argument directory"] =
                    new CompletionHint(CompletionKind.Directory),
                ["mn notebooks export argument directory"] =
                    new CompletionHint(CompletionKind.Directory),
                ["mn notebooks import option --on-conflict"] =
                    new CompletionHint(
                        CompletionKind.Values,
                        "fail",
                        "skip",
                        "replace"),
                ["mn notebooks export option --name-conflict"] =
                    new CompletionHint(
                        CompletionKind.Values,
                        "fail",
                        "id-suffix"),
                ["mn notebooks metadata option --read-only"] =
                    new CompletionHint(
                        CompletionKind.Values,
                        "true",
                        "false")
            };

        static readonly CompletionHint DirectoryHint =
            new CompletionHint(CompletionKind.Directory);

        internal static string Generate(CommandLineApplication root)
        {
            if (root == null)
                throw new ArgumentNullException(nameof(root));
            if (root.Parent != null)
                throw new ArgumentException(
                    "Completion generation requires the root command.",
                    nameof(root));

            var output = new StringBuilder();
            output.Append("#compdef ")
                .Append(EscapeIdentifier(root.Name))
                .Append('\n')
                .Append('\n')
                .Append("# Generated by `")
                .Append(EscapeComment(root.Name))
                .Append(" completion zsh`. Do not edit.\n\n");

            foreach (var command in EnumerateCommands(root))
                AppendFunction(output, command);

            return output.ToString();
        }

        internal static string EscapeDescription(string value)
        {
            return Normalize(value)
                .Replace("\\", "\\\\", StringComparison.Ordinal)
                .Replace(":", "\\:", StringComparison.Ordinal)
                .Replace("[", "\\[", StringComparison.Ordinal)
                .Replace("]", "\\]", StringComparison.Ordinal);
        }

        internal static string QuoteWord(string value)
        {
            return "'" + (value ?? string.Empty)
                .Replace("'", "'\\''", StringComparison.Ordinal) + "'";
        }

        static IEnumerable<CommandLineApplication> EnumerateCommands(
            CommandLineApplication command)
        {
            yield return command;
            foreach (var child in command.Commands.Where(IsVisible))
            {
                foreach (var descendant in EnumerateCommands(child))
                    yield return descendant;
            }
        }

        static void AppendFunction(
            StringBuilder output,
            CommandLineApplication command)
        {
            output.Append(FunctionName(command))
                .Append("() {\n")
                .Append("  local context state state_descr line\n")
                .Append("  typeset -A opt_args\n\n")
                .Append("  _arguments -C \\\n");

            var specifications = BuildSpecifications(command).ToArray();
            for (var index = 0; index < specifications.Length; index++)
            {
                output.Append("    ")
                    .Append(QuoteWord(specifications[index]));
                if (index < specifications.Length - 1)
                    output.Append(" \\\n");
                else
                    output.Append('\n');
            }

            var children = command.Commands.Where(IsVisible).ToArray();
            if (children.Length > 0)
                AppendSubcommandDispatch(output, children);

            output.Append("}\n\n");
        }

        static IEnumerable<string> BuildSpecifications(
            CommandLineApplication command)
        {
            foreach (var option in command.GetOptions().Where(IsVisible))
            {
                foreach (var specification in BuildOptionSpecifications(
                    command,
                    option))
                {
                    yield return specification;
                }
            }

            var children = command.Commands.Where(IsVisible).ToArray();
            if (children.Length > 0)
            {
                yield return "1:command:->command";
                yield return "*::argument:->arguments";
                yield break;
            }

            for (var index = 0; index < command.Arguments.Count; index++)
            {
                var argument = command.Arguments[index];
                if (!IsVisible(argument))
                    continue;

                yield return BuildArgumentSpecification(
                    command,
                    argument,
                    index + 1);
            }
        }

        static IEnumerable<string> BuildOptionSpecifications(
            CommandLineApplication command,
            CommandOption option)
        {
            var names = OptionNames(option).ToArray();
            var repeatable = option.OptionType == CommandOptionType.MultipleValue;
            var exclusion = repeatable
                ? string.Empty
                : "(" + string.Join(" ", names) + ")";
            var description = EscapeDescription(option.Description);
            var suffix = "[" + description + "]";

            if (option.OptionType != CommandOptionType.NoValue)
            {
                var valueName = string.IsNullOrWhiteSpace(option.ValueName)
                    ? "value"
                    : Normalize(option.ValueName).ToLowerInvariant();
                suffix += ":" + EscapeDescription(valueName) + ":" +
                    CompletionAction(GetOptionHint(command, option));
            }

            foreach (var name in names)
            {
                yield return (repeatable ? "*" : exclusion) + name + suffix;
            }
        }

        static string BuildArgumentSpecification(
            CommandLineApplication command,
            CommandArgument argument,
            int position)
        {
            var prefix = argument.MultipleValues ? "*" : position.ToString();
            return prefix + ":" + EscapeDescription(argument.Name) + ":" +
                CompletionAction(GetArgumentHint(command, argument));
        }

        static void AppendSubcommandDispatch(
            StringBuilder output,
            IReadOnlyList<CommandLineApplication> children)
        {
            output.Append("\n  case $state in\n")
                .Append("    command)\n")
                .Append("      local -a commands\n")
                .Append("      commands=(\n");
            foreach (var child in children)
            {
                output.Append("        ")
                    .Append(QuoteWord(
                        EscapeDescription(child.Name) + ":" +
                        EscapeDescription(child.Description)))
                    .Append('\n');
            }
            output.Append("      )\n")
                .Append("      _describe 'command' commands\n")
                .Append("      ;;\n")
                .Append("    arguments)\n")
                .Append("      case $line[1] in\n");

            foreach (var child in children)
            {
                output.Append("        ")
                    .Append(EscapeIdentifier(child.Name))
                    .Append(")\n")
                    .Append("          local command_index=${words[(i)")
                    .Append(EscapeIdentifier(child.Name))
                    .Append("]}\n")
                    .Append("          words=(\"${(@)words[$command_index,-1]}\")\n")
                    .Append("          (( CURRENT -= command_index - 1 ))\n")
                    .Append("          ")
                    .Append(FunctionName(child))
                    .Append("\n")
                    .Append("          ;;\n");
            }

            output.Append("      esac\n")
                .Append("      ;;\n")
                .Append("  esac\n");
        }

        static CompletionHint GetOptionHint(
            CommandLineApplication command,
            CommandOption option)
        {
            if (string.Equals(option.LongName, "workspace", StringComparison.Ordinal))
                return DirectoryHint;

            var name = option.LongName == null
                ? OptionNames(option).First()
                : "--" + option.LongName;
            var key = CommandPath(command) + " option " + name;
            return Hints.TryGetValue(key, out var hint) ? hint : null;
        }

        static CompletionHint GetArgumentHint(
            CommandLineApplication command,
            CommandArgument argument)
        {
            var key = CommandPath(command) + " argument " + argument.Name;
            return Hints.TryGetValue(key, out var hint) ? hint : null;
        }

        static string CompletionAction(CompletionHint hint)
        {
            if (hint == null || hint.Kind == CompletionKind.None)
                return string.Empty;

            return hint.Kind switch
            {
                CompletionKind.File => "_files",
                CompletionKind.Directory => "_directories",
                CompletionKind.Values => "(" + string.Join(" ", hint.Values) + ")",
                _ => throw new ArgumentOutOfRangeException(nameof(hint))
            };
        }

        static IEnumerable<string> OptionNames(CommandOption option)
        {
            if (!string.IsNullOrWhiteSpace(option.SymbolName))
                yield return "-" + option.SymbolName;
            if (!string.IsNullOrWhiteSpace(option.ShortName))
                yield return "-" + option.ShortName;
            if (!string.IsNullOrWhiteSpace(option.LongName))
                yield return "--" + option.LongName;
        }

        static string FunctionName(CommandLineApplication command)
        {
            return "_" + string.Join(
                "_",
                CommandNames(command).Select(EscapeIdentifier));
        }

        static string CommandPath(CommandLineApplication command)
        {
            return string.Join(" ", CommandNames(command));
        }

        static IEnumerable<string> CommandNames(CommandLineApplication command)
        {
            var names = new Stack<string>();
            for (var current = command; current != null; current = current.Parent)
                names.Push(current.Name);
            return names;
        }

        static bool IsVisible(CommandLineApplication command)
        {
            return command.ShowInHelpText;
        }

        static bool IsVisible(CommandOption option)
        {
            return option.ShowInHelpText;
        }

        static bool IsVisible(CommandArgument argument)
        {
            return argument.ShowInHelpText;
        }

        static string EscapeIdentifier(string value)
        {
            if (string.IsNullOrWhiteSpace(value) ||
                value.Any(character =>
                    !char.IsAsciiLetterOrDigit(character) &&
                    character != '_' &&
                    character != '-'))
            {
                throw new InvalidOperationException(
                    "Command metadata contains an unsupported zsh identifier.");
            }

            return value;
        }

        static string EscapeComment(string value)
        {
            return Normalize(value).Replace("`", string.Empty, StringComparison.Ordinal);
        }

        static string Normalize(string value)
        {
            if (string.IsNullOrWhiteSpace(value))
                return string.Empty;

            return string.Join(
                " ",
                value.Split(
                    (char[])null,
                    StringSplitOptions.RemoveEmptyEntries));
        }
    }
}
